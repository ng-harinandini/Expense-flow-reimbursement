def test_pdf_parser_logs_when_ocr_is_entirely_unavailable(monkeypatch) -> None:
    """Regression: an entirely-unavailable OCR path used to drop empty pages with no log line at
    all — the one degraded path in this parser that didn't log, and the most consequential one: a
    fully-scanned PDF would parse to an empty document with nothing explaining why.

    Uses a handler attached directly to the named logger rather than ``caplog``: when this test
    file runs alongside any test that touches the database, the Alembic migration those tests
    trigger calls ``logging.config.fileConfig`` with its default ``disable_existing_loggers=True``,
    which leaves every logger created before that point (module import time, here) with
    ``disabled = True`` for the rest of the session — including whenever pytest's own ``caplog``
    handler would otherwise have received the record.
    """
    monkeypatch.setattr("app.ai.parsing.pdf.is_ocr_available", lambda: False)
    content = multi_page_pdf("Page one text.", "")

    records: list[logging.LogRecord] = []

    class Collector(logging.Handler):
        def emit(self, record: logging.LogRecord) -> None:
            records.append(record)

    target = logging.getLogger("app.ai.parsing.pdf")
    handler = Collector(level=logging.WARNING)
    previous_disabled = target.disabled
    target.addHandler(handler)
    target.disabled = False
    try:
        text, sections = PdfParser().parse(raw(content, "a.pdf"))
    finally:
        target.removeHandler(handler)
        target.disabled = previous_disabled

    assert "Page one text." in text
    assert len(sections) == 1
    assert any("pdf_pages_dropped_no_ocr" in record.getMessage() for record in records)


