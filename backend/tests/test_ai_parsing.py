def test_pdf_parser_ocr_falls_back_only_for_empty_pages(monkeypatch) -> None:
    """A mixed document: page 2 has no text layer. Only page 2 should be routed to OCR."""
    calls: list[bytes] = []

    def fake_ocr(content: bytes, *, region=None):
        calls.append(content)
        return "OCR'd scanned text"

    monkeypatch.setattr("app.ai.parsing.pdf.is_ocr_available", lambda: True)
    monkeypatch.setattr("app.ai.parsing.pdf.ocr_text_from_bytes", fake_ocr)

    content = multi_page_pdf("Page one text.", "", "Page three text.")
    text, sections = PdfParser().parse(raw(content, "a.pdf"))

    assert len(calls) == 1  # only the empty page was OCR'd
    assert "OCR'd scanned text" in text
    assert "Page one text." in text
    assert "Page three text." in text


