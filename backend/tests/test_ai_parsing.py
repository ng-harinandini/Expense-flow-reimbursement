class _StubParser(BaseDocumentParser):
    def __init__(self, *, fail: bool = False, **kwargs) -> None:
        super().__init__(name="stub", mime_types=frozenset({"text/x-stub"}),
                          extensions=frozenset({".stub"}), **kwargs)
        self._fail = fail

    def is_available(self) -> bool:
        return True

    def _parse(self, document: RawDocument):
        if self._fail:
            raise ValueError("boom")
        return "parsed", single_section("parsed")


