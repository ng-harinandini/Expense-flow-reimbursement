    breakdown = quality.score_with_breakdown("A reasonably normal sentence of text.")
    assert breakdown.score == pytest.approx(
        30 * breakdown.length_score
        + 30 * breakdown.alnum_ratio_score
        + 20 * breakdown.word_shape_score
        + 10 * breakdown.structure_score
        + 10 * breakdown.language_score,
        abs=1e-6,
    )
