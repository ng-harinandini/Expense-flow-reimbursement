def _one_page_pdf(text: str) -> bytes:
    header = (
        "%PDF-1.4\n"
        "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
        "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n"
        "3 0 obj\n<< /Type /Page /Parent 2 0 R "
        "/Resources << /Font << /F1 4 0 R >> >> "
        "/MediaBox [0 0 300 150] /Contents 5 0 R >>\nendobj\n"
        "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n"
    )
    escaped = text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
    stream = f"BT /F1 12 Tf 20 100 Td ({escaped}) Tj ET" if text else ""
    body = f"5 0 obj\n<< /Length {len(stream)} >>\nstream\n{stream}\nendstream\nendobj\n"
    trailer = (
        "xref\n0 6\n0000000000 65535 f \ntrailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n0\n%%EOF"
    )
    return (header + body + trailer).encode("latin-1")


def multi_page_pdf(*page_texts: str) -> bytes:
    from pypdf import PdfReader, PdfWriter

    writer = PdfWriter()
    for text in page_texts:
        reader = PdfReader(io.BytesIO(_one_page_pdf(text)))
        writer.add_page(reader.pages[0])
    buffer = io.BytesIO()
    writer.write(buffer)
    return buffer.getvalue()


def _docx_bytes(headings_and_paragraphs: list[tuple[int, str, str]]) -> bytes:
    from docx import Document

    doc = Document()
    for level, heading, body in headings_and_paragraphs:
        doc.add_heading(heading, level=level)
        doc.add_paragraph(body)
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def _xlsx_bytes(sheets: dict[str, list[list[Any]]]) -> bytes:
    from openpyxl import Workbook

    workbook = Workbook()
    workbook.remove(workbook.active)
    for name, rows in sheets.items():
        sheet = workbook.create_sheet(title=name)
        for row in rows:
            sheet.append(row)
    buffer = io.BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


